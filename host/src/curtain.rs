//! Шторка (слайс 4.2c): чёрные окна поверх физических мониторов хоста,
//! исключённые из захвата экрана, плюс блокировка локального ввода. Владелец
//! за удалённым клиентом видит рабочий стол, а тот, кто сидит у машины, --
//! только чёрный экран.
//!
//! Модуль платформенно-независим: он описывает лишь трейт `Curtain`.
//! Реализация (macOS: окна `NSWindow` и перехват событий ввода) живёт в
//! `platform::macos` и подставляется в `HostContext::curtain`; пока её нет,
//! везде `None`.
//!
//! Порядок в конце сеанса с включённой шторкой -- строго `lock_screen`, затем
//! `hide`: рабочий стол не должен открыться без присмотра в тот момент, когда
//! шторку уже убрали, а экран ещё не заблокирован. Все методы блокирующие
//! (реализация ходит в главный поток), поэтому из async-кода их зовут только
//! через `tokio::task::spawn_blocking`.

/// Шторка хоста. См. описание модуля.
pub trait Curtain: Send + Sync {
    /// Показывает шторку на всех дисплеях. Возвращает CGWindowID окон
    /// шторки -- их надо исключить из захвата. Блокирующий вызов
    /// (реализация ходит в главный поток).
    fn show(&self) -> anyhow::Result<Vec<u32>>;
    /// Убирает шторку и разблокирует локальный ввод. Идемпотентно.
    fn hide(&self);
    /// Блокирует экран; возвращает, когда блокировка уже наступила (или по
    /// таймауту реализации).
    fn lock_screen(&self) -> anyhow::Result<()>;
}
